// backend/models/<entity>.model.js: one Mongoose schema, only the fields the screenshots show.
const TYPE = {
  string: "String",
  email: "String",
  number: "Number",
  boolean: "Boolean",
  date: "Date",
  enum: "String",
  ref: "mongoose.Schema.Types.ObjectId",
};

function fieldLine(f, pascal) {
  const options = [`type: ${TYPE[f.type]}`];
  if (f.type === "ref") options.push(`ref: ${JSON.stringify(pascal(f.ref))}`);
  if (f.required) options.push("required: true");
  if (f.type === "string" || f.type === "email") options.push("trim: true");
  if (f.type === "email") options.push("lowercase: true");
  if (f.type === "enum") options.push(`enum: ${JSON.stringify(f.options)}`);
  if (typeof f.min === "number") options.push(`min: ${f.min}`);
  if (typeof f.max === "number") options.push(`max: ${f.max}`);
  return `    // ${f.evidence}\n    ${f.name}: { ${options.join(", ")} },`;
}

export default ({ entity, comment, pascal }) => {
  const lines = entity.fields.map((f) => fieldLine({ ...f, evidence: comment(f.evidence) }, pascal));
  if (entity.endpoints.delete?.soft) {
    lines.push(`    // ${comment(entity.endpoints.delete.evidence)}: deleted records are kept and hidden\n    deletedAt: { type: Date, default: null },`);
  }
  return `// ${comment(entity.label)}: generated by AndarKaCode from screenshots.
import mongoose from "mongoose";

const schema = new mongoose.Schema(
  {
${lines.join("\n")}
  },
  {
    timestamps: true,
    collection: ${JSON.stringify(entity.plural)},
    toJSON: {
      versionKey: false,
      transform(_doc, ret) {
        ret.id = ret._id.toString();
        delete ret._id;
        return ret;
      },
    },
  }
);

export const ${entity.Model} = mongoose.models.${entity.Model} ?? mongoose.model(${JSON.stringify(entity.Model)}, schema);
`;
};
