// backend/server.js of the generated app: Express, MongoDB, /health, and the pages from the screenshots.
export default ({ app }) => `// ${app.title}: generated by AndarKaCode from screenshots.
import express from "express";
import mongoose from "mongoose";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));

export const app = express();
app.use(express.json());

app.get("/health", (_req, res) => {
  res.json({ ok: true, db: mongoose.connection.readyState === 1 });
});

// The pages built from the screenshots, served from the same origin as the API (no CORS needed).
app.use(express.static(path.join(here, "..", "frontend")));

// Anything unexpected: answer in JSON.
app.use((err, _req, res, _next) => {
  console.error(err);
  res.status(err.status ?? 500).json({ error: err.status ? err.message : "Internal error" });
});

export async function start({ port = Number(process.env.PORT ?? 3000), mongoUri = process.env.MONGODB_URI } = {}) {
  if (!mongoUri) throw new Error("Set MONGODB_URI (see .env.example)");
  await mongoose.connect(mongoUri);
  return app.listen(port, () => console.log(\`Listening on http://localhost:\${port}\`));
}

// Run directly with \`npm start\`; tests import \`app\` instead.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await start();
`;
