// backend/server.js of the generated app: Express, MongoDB, /health, the API, and the pages from the screenshots.
export default ({ app, spec }) => {
  const imports = spec.entities.map((e) => `import { router as ${e.name}Routes } from "./routes/${e.name}.routes.js";`);
  const mounts = spec.entities.map((e) => `app.use(${JSON.stringify(`/api/${e.plural}`)}, ${e.name}Routes);`);
  if (spec.stats.length) {
    imports.push('import { router as statsRoutes } from "./routes/stats.routes.js";');
    mounts.push('app.use("/api/stats", statsRoutes);');
  }

  return `// ${app.title}: generated by AndarKaCode from screenshots.
import express from "express";
import mongoose from "mongoose";
import path from "node:path";
import { fileURLToPath } from "node:url";
${imports.join("\n")}

const here = path.dirname(fileURLToPath(import.meta.url));

export const app = express();
app.use(express.json());

app.get("/health", (_req, res) => {
  res.json({ ok: true, db: mongoose.connection.readyState === 1 });
});

${mounts.join("\n")}
app.use("/api", (_req, res) => res.status(404).json({ error: "Not found" }));

// The pages built from the screenshots, served from the same origin as the API (no CORS needed).
app.use(express.static(path.join(here, "..", "frontend")));

// Database and unexpected errors: always answer in JSON.
app.use((err, _req, res, _next) => {
  if (err.name === "ValidationError" || err.name === "CastError") return res.status(400).json({ error: err.message });
  if (err.code === 11000) return res.status(409).json({ error: "A record with this value already exists" });
  console.error(err);
  res.status(err.status ?? 500).json({ error: err.status ? err.message : "Internal error" });
});

export async function start({ port = Number(process.env.PORT ?? 3000), mongoUri = process.env.MONGODB_URI } = {}) {
  if (!mongoUri) throw new Error("Set MONGODB_URI (see .env.example)");
  await mongoose.connect(mongoUri);
  return app.listen(port, () => console.log(\`Listening on http://localhost:\${port}\`));
}

// Run directly with \`npm start\`; tests import \`app\` instead.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await start();
`;
};
