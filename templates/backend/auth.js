// backend/auth/passwords.js: passwords are never stored, only a salted scrypt hash.
export const passwords = () => String.raw`// Passwords are never stored: only a salted scrypt hash, written as "scrypt$<salt>$<hash>".
import { randomBytes, scrypt, timingSafeEqual } from "node:crypto";
import { promisify } from "node:util";

const scryptAsync = promisify(scrypt);
const KEY_LENGTH = 64;

export async function hashPassword(password) {
  const salt = randomBytes(16).toString("base64url");
  const hash = await scryptAsync(String(password), salt, KEY_LENGTH);
  return "scrypt$" + salt + "$" + hash.toString("base64url");
}

export async function verifyPassword(password, stored) {
  const [scheme, salt, expected] = String(stored ?? "").split("$");
  if (scheme !== "scrypt" || !salt || !expected) return false;
  const actual = await scryptAsync(String(password), salt, KEY_LENGTH);
  const expectedBytes = Buffer.from(expected, "base64url");
  return expectedBytes.length === actual.length && timingSafeEqual(expectedBytes, actual);
}
`;

