// backend/models/loginSession.model.js
export const loginSessionModel = () => String.raw`// One row per login. Only a SHA-256 fingerprint of the token is stored, so a copy of the
// database can't be used to log in. MongoDB deletes sessions once they expire.
import mongoose from "mongoose";

const schema = new mongoose.Schema(
  {
    tokenHash: { type: String, required: true, unique: true },
    account: { type: mongoose.Schema.Types.ObjectId, ref: "Account", required: true },
    expiresAt: { type: Date, required: true },
  },
  { timestamps: true, collection: "loginSessions" }
);
schema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });

export const LoginSession = mongoose.models.LoginSession ?? mongoose.model("LoginSession", schema);
`;

// backend/auth/middleware.js: every /api route except /api/auth needs a valid token.
export const middleware = () => String.raw`// Every data route needs "Authorization: Bearer <token>" from a login that has not expired.
import { createHash } from "node:crypto";
import { LoginSession } from "../models/loginSession.model.js";

export const tokenHash = (token) => createHash("sha256").update(token).digest("hex");

export async function requireLogin(req, res, next) {
  const header = req.get("Authorization") ?? "";
  const token = header.startsWith("Bearer ") ? header.slice(7).trim() : "";
  if (!token) return res.status(401).json({ error: "Please log in" });
  const session = await LoginSession.findOne({ tokenHash: tokenHash(token), expiresAt: { $gt: new Date() } }).populate("account");
  if (!session?.account) return res.status(401).json({ error: "Please log in" });
  req.account = session.account;
  req.loginSession = session;
  next();
}
`;

