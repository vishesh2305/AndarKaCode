// backend/routes/stats.routes.js: GET /api/stats with exactly the numbers on the screenshots' stat cards.
// Each key matches the page's data-stat marker (the card label in camelCase).
export default ({ spec, comment, pascal, camelCase }) => {
  const isSoft = (name) => Boolean(spec.entities.find((e) => e.name === name)?.endpoints.delete?.soft);
  const models = [...new Set(spec.stats.filter((s) => s.entity && s.metric !== "custom").map((s) => s.entity))];

  const entries = spec.stats.map((s) => {
    const key = camelCase(s.label);
    const M = s.entity && pascal(s.entity);
    const match = { ...(s.entity && isSoft(s.entity) && { deletedAt: null }), ...(s.where ?? {}) };
    if (s.metric === "count") {
      return `    // ${comment(s.evidence)}\n    ${key}: await ${M}.countDocuments(${JSON.stringify(match)}),`;
    }
    if (s.metric === "sum") {
      return `    // ${comment(s.evidence)}\n    ${key}: (await ${M}.aggregate([{ $match: ${JSON.stringify(match)} }, { $group: { _id: null, total: { $sum: ${JSON.stringify(`$${s.field}`)} } } }]))[0]?.total ?? 0,`;
    }
    return `    // ${comment(s.evidence)}: how it is calculated is not known yet (see the spec's open questions)\n    ${key}: null,`;
  });

  return `// The numbers on the screenshots' stat cards: generated by AndarKaCode.
import { Router } from "express";
${models.map((m) => `import { ${pascal(m)} } from "../models/${m}.model.js";`).join("\n")}

export const router = Router();

router.get("/", async (_req, res) => {
  res.json({
${entries.join("\n")}
  });
});
`;
};
