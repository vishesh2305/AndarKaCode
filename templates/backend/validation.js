// backend/validation/<entity>.validation.js: checks request bodies before they reach the database.
// Only the conversions the entity's field types need are generated.
const CONVERT = {
  string: `    case "string":
      return { value: String(raw).trim() };`,
  email: `    case "email": {
      const v = String(raw).trim().toLowerCase();
      return EMAIL.test(v) ? { value: v } : { error: "must be an email address" };
    }`,
  number: `    case "number": {
      const v = typeof raw === "number" ? raw : Number(String(raw).replace(/[\\s,$€£₹]/g, ""));
      return Number.isFinite(v) ? { value: v } : { error: "must be a number" };
    }`,
  boolean: `    case "boolean":
      if (raw === true || raw === "true") return { value: true };
      if (raw === false || raw === "false") return { value: false };
      return { error: "must be true or false" };`,
  date: `    case "date": {
      const d = new Date(raw);
      return Number.isNaN(d.getTime()) ? { error: "must be a date" } : { value: d };
    }`,
  enum: `    case "enum":
      return rule.options.includes(raw) ? { value: raw } : { error: \`must be one of: \${rule.options.join(", ")}\` };`,
  ref: `    case "ref":
      return OBJECT_ID.test(String(raw)) ? { value: String(raw) } : { error: "must be the id of an existing record" };`,
};

export default ({ entity, comment }) => {
  const types = [...new Set(entity.fields.map((f) => f.type))];
  const rules = entity.fields.map((f) => {
    const rule = { type: f.type, ...(f.required && { required: true }), ...(f.type === "enum" && { options: f.options }) };
    return `  ${f.name}: ${JSON.stringify(rule).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ")}, // ${comment(f.evidence)}`;
  });
  const constants = [
    types.includes("email") && "const EMAIL = /^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/;",
    types.includes("ref") && "const OBJECT_ID = /^[a-f0-9]{24}$/i;",
  ].filter(Boolean);

  return `// Checks request bodies for ${comment(entity.label)} before they reach the database.
// Generated by AndarKaCode: only the fields the screenshots show; anything else is ignored.
${constants.length ? constants.join("\n") + "\n\n" : ""}const FIELDS = {
${rules.join("\n")}
};

function convert(rule, raw) {
  switch (rule.type) {
${types.map((t) => CONVERT[t]).join("\n")}
  }
}

/** Returns { ok, errors: { field: message }, value }. partial: true for updates (missing fields stay unchanged). */
export function validate${entity.Model}(body, { partial = false } = {}) {
  const errors = {};
  const value = {};
  for (const [name, rule] of Object.entries(FIELDS)) {
    const raw = body?.[name];
    if (raw === undefined || raw === null || raw === "") {
      if (rule.required && !partial) errors[name] = "is required";
      continue;
    }
    const result = convert(rule, raw);
    if (result.error) errors[name] = result.error;
    else value[name] = result.value;
  }
  return { ok: Object.keys(errors).length === 0, errors, value };
}
`;
};
