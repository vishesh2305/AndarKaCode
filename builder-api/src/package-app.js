// The generated app as the user receives it: backend (templates) + pages (Laptop B) + README + spec.
import { readdir, readFile, stat } from "node:fs/promises";
import path from "node:path";
import { REPO_ROOT } from "./storage.js";
import { createZip } from "./zip.js";

const toPosix = (p) => p.split(path.sep).join("/");

/** Every file of a generated app folder, as [{ path: "backend/server.js", size }]. */
export async function listAppFiles(appDir) {
  const files = [];
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (entry.name === "node_modules") continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else files.push({ path: toPosix(path.relative(appDir, full)), size: (await stat(full)).size });
    }
  }
  await walk(appDir);
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

/** The absolute path of a file inside the app folder, or null if the path tries to leave it. */
export function safeAppPath(appDir, relPath) {
  const rel = String(relPath ?? "");
  if (!rel || rel.includes("\\") || path.isAbsolute(rel) || /^[a-zA-Z]:/.test(rel) || rel.split("/").includes("..")) return null;
  const full = path.resolve(appDir, rel);
  return full.startsWith(path.resolve(appDir) + path.sep) ? full : null;
}

export const slug = (name) => String(name).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "generated-app";

// What was built and why: every item with its screenshot evidence.
export function readme({ project, contract, pages }) {
  const spec = contract.body;
  const lines = [
    `# ${project.name}`,
    "",
    `Generated by AndarKaCode from ${pages.length} screenshot${pages.length === 1 ? "" : "s"} (App Spec version ${contract.version}, fingerprint \`${contract.hash.slice(0, 12)}\`).`,
    "Everything here was built because a screenshot shows it; each item below says where it came from (s1 = screenshot 1).",
    "",
    "## Run it",
    "",
    "1. Install Node.js 22 or newer and MongoDB.",
    "2. `npm install`",
    "3. Copy `.env.example` to `.env` and adjust it.",
    "4. `npm start`, then open http://localhost:3000",
    "",
    "Tests: `MONGODB_URI_TEST=mongodb://127.0.0.1:27017/app_test npm test` (that database is emptied).",
    "",
    "## Pages",
    "",
    ...pages.map((p) => `- \`frontend/page-${p.screenshot}.html\`: from screenshot ${p.screenshot}${p.screenshot === pages[0].screenshot ? " (also `index.html`)" : ""}`),
    "",
    "The pages show the screenshots' sample data. Connecting their buttons to the API is the next AndarKaCode step.",
    "",
    "## What was built, and why",
  ];
  for (const e of spec.entities) {
    lines.push("", `### ${e.label} (\`/api/${e.plural}\`)`, "");
    for (const f of e.fields) lines.push(`- field \`${f.name}\` (${f.type}${f.required ? ", required" : ""}): ${f.evidence}`);
    for (const [key, endpoint] of Object.entries(e.endpoints)) lines.push(`- ${key}: ${endpoint.evidence}`);
    for (const o of spec.operations.filter((x) => x.entity === e.name)) {
      lines.push(`- button "${o.button}" (${o.kind === "custom" ? "not available yet" : o.kind}): ${o.evidence}`);
    }
  }
  if (spec.stats.length) {
    lines.push("", "### Stat cards (`/api/stats`)", "");
    for (const s of spec.stats) lines.push(`- ${s.label} (${s.metric}): ${s.evidence}`);
  }
  if (spec.auth) {
    lines.push("", "### Login (`/api/auth`)", "", `- login: ${spec.auth.login.evidence}`);
    if (spec.auth.signup) lines.push(`- sign-up: ${spec.auth.signup.evidence}`);
    if (spec.auth.me) lines.push(`- current user and logout: ${spec.auth.me.evidence}`);
    if (spec.auth.roles) lines.push(`- roles ${spec.auth.roles.values.join(", ")}: ${spec.auth.roles.evidence}`);
  }
  return lines.join("\n") + "\n";
}

/** Zip of the whole app: generated backend + pages + screenshots + README + spec. */
export async function appArchive({ project, contract, backendJob, frontendJobs, screenshots }) {
  const appDir = path.join(REPO_ROOT, backendJob.artifactPath);
  const entries = [];
  for (const file of await listAppFiles(appDir)) entries.push({ name: file.path, data: await readFile(path.join(appDir, file.path)) });

  const pages = contract.body.pages;
  for (const page of pages) {
    const job = frontendJobs.find((j) => j.page === page.screenshot);
    if (!job) continue;
    const html = await readFile(path.join(REPO_ROOT, job.artifactPath));
    entries.push({ name: `frontend/page-${page.screenshot}.html`, data: html });
    if (page.screenshot === pages[0].screenshot) entries.push({ name: "frontend/index.html", data: html });
  }
  for (const [i, shot] of screenshots.entries()) {
    entries.push({ name: `screenshots/screenshot-${i + 1}.png`, data: await readFile(path.join(REPO_ROOT, shot.path)) });
  }
  entries.push({ name: "README.md", data: readme({ project, contract, pages }) });
  entries.push({ name: "app-spec.json", data: JSON.stringify({ version: contract.version, hash: contract.hash, spec: contract.body }, null, 2) + "\n" });
  return createZip(entries);
}
